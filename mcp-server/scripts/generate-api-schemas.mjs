import { readFileSync, writeFileSync } from 'node:fs';

const DEFAULT_SOURCE = 'https://post.adaptlypost.com/post/api/v1/openapi.json';
const OUTPUT = new URL('../src/api-schemas.ts', import.meta.url);

const source = process.argv[2] ?? DEFAULT_SOURCE;
const document = source.startsWith('http')
  ? await (await fetch(source)).json()
  : JSON.parse(readFileSync(source, 'utf8'));

const components = document.components.schemas;
const refName = (ref) => ref.replace('#/components/schemas/', '');

const resolve = (schema) => (schema.$ref ? components[refName(schema.$ref)] : schema);

const quote = (text) => JSON.stringify(text);

const singleRef = (schema) =>
  schema.allOf?.length === 1 && schema.allOf[0].$ref ? schema.allOf[0] : undefined;

const flattenAllOf = (schema) => {
  const properties = {};
  for (const part of schema.allOf) Object.assign(properties, resolve(part).properties ?? {});
  return { type: 'object', properties, description: schema.description };
};

let referenced = new Set();

function expression(schema) {
  const ref = schema.$ref ? schema : singleRef(schema);
  if (ref) {
    referenced.add(refName(ref.$ref));
    return refName(ref.$ref);
  }
  if (schema.allOf) return expression(flattenAllOf(schema));
  if (schema.oneOf || schema.anyOf) {
    const options = (schema.oneOf ?? schema.anyOf).map(expression);
    return `z.union([${options.join(', ')}])`;
  }
  if (schema.enum) return `z.string().describe(${quote(`One of: ${schema.enum.join(', ')}`)})`;
  switch (schema.type) {
    case 'string':
      return 'z.string()';
    case 'integer':
    case 'number':
      return 'z.number()';
    case 'boolean':
      return 'z.boolean()';
    case 'array':
      return `z.array(${schema.items ? expression(schema.items) : 'z.unknown()'})`;
    case 'object':
    case undefined: {
      const entries = Object.entries(schema.properties ?? {}).map(([key, value]) => {
        const described = value.description ? `.describe(${quote(value.description)})` : '';
        return `${quote(key)}: ${expression(value)}.nullish()${described}`;
      });
      return `z.object({ ${entries.join(', ')} }).passthrough()`;
    }
    default:
      return 'z.unknown()';
  }
}

const responseSchema = (operation) => {
  for (const [code, response] of Object.entries(operation.responses ?? {})) {
    if (!code.startsWith('2')) continue;
    const schema = response.content?.['application/json']?.schema;
    if (schema) return schema;
  }
  return undefined;
};

const operations = [];
for (const methods of Object.values(document.paths)) {
  for (const operation of Object.values(methods)) {
    const schema = operation?.operationId ? responseSchema(operation) : undefined;
    if (schema) operations.push([operation.operationId, expression(schema)]);
  }
}

const componentCode = new Map();
const componentDependencies = new Map();
const pending = [...referenced];
while (pending.length) {
  const name = pending.pop();
  if (componentCode.has(name)) continue;
  referenced = new Set();
  componentCode.set(name, expression(components[name]));
  componentDependencies.set(name, referenced);
  pending.push(...referenced);
}

const ordered = [];
const visit = (name, trail = []) => {
  if (ordered.includes(name)) return;
  if (trail.includes(name)) throw new Error(`Cyclic schema: ${[...trail, name].join(' -> ')}`);
  for (const dependency of componentDependencies.get(name)) visit(dependency, [...trail, name]);
  ordered.push(name);
};
[...componentCode.keys()].sort().forEach((name) => visit(name));

const lines = [
  `// Generated by scripts/generate-api-schemas.mjs from ${DEFAULT_SOURCE}. Run \`bun run generate:api-schemas\` after the API changes.`,
  "import { z } from 'zod';",
  '',
  ...ordered.map((name) => `const ${name} = ${componentCode.get(name)};\n`),
  'export const apiResponses = {',
  ...operations.map(([id, code]) => `  ${id}: ${code},`),
  '};',
  '',
];

writeFileSync(OUTPUT, lines.join('\n'));
console.log(`Wrote ${operations.length} response schemas and ${ordered.length} components to src/api-schemas.ts`);
